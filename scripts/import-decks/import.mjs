// ─── Main import function ─────────────────────────────────────
async function importAll() {
  console.log('Signing in...');
  const { idToken, uid } = await signIn();
  console.log(`  ✓ Authenticated as: ${uid}`);

  const authorName = 'FluentCards';
  let totalDecks = 0;
  let totalCards = 0;

  for (const lang of LANGUAGES) {
    const deckTypes = [
      { key: 'essentials', title: 'Daily Essentials' },
      { key: 'phrases', title: 'Common Phrases' },
      { key: 'vocabulary', title: 'Core Vocabulary' },
    ];

    for (const deck of deckTypes) {
      const cards = lang[deck.key];
      const deckId = uuidv4();
      const deckName = `${lang.name} — ${deck.title}`;

      console.log(`Creating deck: ${deckName} (${cards.length} cards)`);

      // Write deck document
      const deckWrites = [{
        update: makeDocument(`decks/${deckId}`, {
          id: deckId,
          userId: uid,
          name: deckName,
          description: `Learn ${deck.title.toLowerCase()} in ${lang.name}. Perfect for English speakers starting their ${lang.name} learning journey. ${cards.length} cards covering real-life situations and everyday communication.`,
          createdAt: Date.now(),
          isPublic: true,
          authorName,
        }),
      }];
      await commitWrites(idToken, deckWrites);

      // Write cards in batches of 498
      let batch = [];
      for (const card of cards) {
        const cardId = uuidv4();
        batch.push({
          update: makeDocument(`cards/${cardId}`, makeCardDoc(cardId, uid, deckId, card, lang.code)),
        });

        if (batch.length >= 498) {
          await commitWrites(idToken, batch);
          batch = [];
        }
      }
      if (batch.length > 0) {
        await commitWrites(idToken, batch);
      }

      console.log(`  ✓ "${deckName}" — ${cards.length} cards`);
      totalDecks++;
      totalCards += cards.length;
    }
  }

  console.log(`\n✅ All ${totalDecks} decks imported successfully — ${totalCards} total cards!`);
}

importAll().catch(err => {
  console.error('Import failed:', err);
  process.exit(1);
});
