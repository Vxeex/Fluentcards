// ─── Firestore REST helpers ───────────────────────────────────
function toValue(v) {
  if (v === null || v === undefined) return { nullValue: null };
  if (typeof v === 'string') return { stringValue: v };
  if (typeof v === 'number') {
    return Number.isInteger(v) && Math.abs(v) < 2 ** 53
      ? { integerValue: String(v) }
      : { doubleValue: v };
  }
  if (typeof v === 'boolean') return { booleanValue: v };
  if (v instanceof Date) return { timestampValue: v.toISOString() };
  if (Array.isArray(v)) return { arrayValue: { values: v.map(toValue) } };
  if (typeof v === 'object') {
    const fields = {};
    for (const [k, val] of Object.entries(v)) {
      if (val !== undefined) fields[k] = toValue(val);
    }
    return { mapValue: { fields } };
  }
  return { stringValue: String(v) };
}

function makeDocument(path, obj) {
  const fields = {};
  for (const [k, v] of Object.entries(obj)) {
    if (v !== undefined && v !== null) fields[k] = toValue(v);
  }
  return { name: `projects/${PROJECT_ID}/databases/${DB_ID}/documents/${path}`, fields };
}

async function commitWrites(idToken, writes) {
  const url = `https://firestore.googleapis.com/v1/projects/${PROJECT_ID}/databases/${DB_ID}/documents:commit`;
  const res = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${idToken}`,
    },
    body: JSON.stringify({ writes }),
  });
  if (!res.ok) {
    const err = await res.json();
    throw new Error(`Firestore commit failed: ${err.error?.message || res.status}`);
  }
  return res.json();
}

// ─── Empty FSRS state (fresh card) ────────────────────────────
function emptyFSRS() {
  const now = new Date();
  return {
    due: now.toISOString(),
    stability: 0,
    difficulty: 0,
    elapsed_days: 0,
    scheduled_days: 0,
    reps: 0,
    lapses: 0,
    state: 0,
    last_review: null,
  };
}

function makeCardDoc(cardId, uid, deckId, card, langCode) {
  const fsrs = emptyFSRS();
  return {
    id: cardId,
    userId: uid,
    deckId,
    front: card.f,
    back: card.b,
    language: langCode,
    targetLanguage: 'en-US',
    useMnemonic: true,
    isPublic: true,
    ...fsrs,
  };
}

